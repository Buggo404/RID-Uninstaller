export type MsgKey = keyof typeof en;

export type Lang = "en" | "zh" | "pt";

const dictionaries: Record<Lang, Record<MsgKey, string>> = { en, zh, pt };

/** BCP 47 tags for the page's `lang` attribute and for date formatting. */
export const locales: Record<Lang, string> = { en: "en-US", zh: "zh-CN", pt: "pt-BR" };

export const lang = computed<Lang>(() => {
  if (prefs.lang !== "auto") return prefs.lang;
  const system = navigator.language.toLowerCase();
  return system.startsWith("zh") ? "zh" : system.startsWith("pt") ? "pt" : "en";
});

/** `%s` takes the arguments in order; `%1$s` picks one by position for languages that reorder them. */
export function t(key: MsgKey, ...args: (string | number)[]): string {
  let next = 0;
  return dictionaries[lang.value][key].replace(/%(?:(\d+)\$)?s/g, (_, pos) =>
    String(args[pos ? Number(pos) - 1 : next++] ?? ""),
  );
}
